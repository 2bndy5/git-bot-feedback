#[test]
fn log_groups_and_output_variables() {
    unsafe {
        env::set_var("CI_API_V4_URL", "https://gitlab.example.com/api/v4");
        env::set_var("CI_PROJECT_ID", PROJECT_ID);
        env::set_var("CI_COMMIT_SHA", SHA);
    }
    logger_init();
    log::set_max_level(log::LevelFilter::Debug);
    let client = GitlabApiClient::new().unwrap();
    client.start_log_group("clang-tidy (v18)");
    client.end_log_group("clang-tidy (v18)");
    let var = OutputVariable {
        name: "checks-failed".to_string(),
        value: "3".to_string(),
    };
    client.write_output_variables(&[var]).unwrap();
    let logs = take_logs();
    const ERASE_LINE: &str = "\x1b[0K";
    assert!(logs.iter().any(|l| {
        l.starts_with(&format!("{ERASE_LINE}section_start:"))
            && l.ends_with(&format!(
                ":clang-tidy__v18_[collapsed=true]\r{ERASE_LINE}clang-tidy (v18)"
            ))
    }));
    assert!(logs.iter().any(|l| {
        l.starts_with(&format!("{ERASE_LINE}section_end:"))
            && l.ends_with(&format!(":clang-tidy__v18_\r{ERASE_LINE}"))
    }));
    assert!(logs.iter().any(|l| l.ends_with("checks-failed: 3")));
    let bad_var = OutputVariable {
        name: "1st".to_string(),
        value: "value".to_string(),
    };
    assert!(client.write_output_variables(&[bad_var]).is_err());
}

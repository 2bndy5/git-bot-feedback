const MARKER: &str = "<!-- git-bot-feedback -->\n";
const PROJECT_ID: &str = "42";
const FORK_PROJECT_ID: &str = "13";
const SHA: &str = "deadbeef";
const MR: u64 = 7;
const TOKEN: &str = "123456";
const RESET_RATE_LIMIT_HEADER: &str = "ratelimit-reset";
const REMAINING_RATE_LIMIT_HEADER: &str = "ratelimit-remaining";
/// The IDs of existing bot comments (oldest first).
const BOT_COMMENTS: [u64; 3] = [101, 102, 201];

struct TestParams {
    event_t: EventType,
    comment_policy: CommentPolicy,
    comment_kind: CommentKind,
    no_lgtm: bool,
    locked_mr: bool,
    fail_get_mr: bool,
    fail_get_existing_comments: bool,
    bad_existing_comments: bool,
    fail_posting: bool,
    rate_limited: bool,
    no_token: bool,
}

impl Default for TestParams {
    fn default() -> Self {
        Self {
            event_t: EventType::PullRequest,
            comment_policy: CommentPolicy::Update,
            comment_kind: CommentKind::Concerns,
            no_lgtm: false,
            locked_mr: false,
            fail_get_mr: false,
            fail_get_existing_comments: false,
            bad_existing_comments: false,
            fail_posting: false,
            rate_limited: false,
            no_token: false,
        }
    }
}

fn note(id: u64, body: &str) -> serde_json::Value {
    json!({
        "id": id,
        "body": body,
        "author": {"id": 99, "username": "project_42_bot"},
        "system": false,
        "resolvable": false,
    })
}

/// A page of existing comments; the bot's comments are mixed with other notes.
fn existing_comments(page: u8) -> serde_json::Value {
    if page == 1 {
        json!([
            note(100, "A user's comment"),
            note(BOT_COMMENTS[0], &format!("{MARKER}An old bot comment")),
            // notes from a review posted by the bot are not thread comments
            {
                "id": 150,
                "type": "DiffNote",
                "body": format!("{MARKER}A review comment"),
                "author": {"id": 99, "username": "project_42_bot"},
                "position": {"new_path": "src/lib.rs", "new_line": 3},
                "system": false,
                "resolvable": true,
                "resolved": false,
            },
            note(
                151,
                &format!("{MARKER}<!-- review summary -->\nA review summary"),
            ),
            note(BOT_COMMENTS[1], &format!("{MARKER}Another old bot comment")),
        ])
    } else {
        json!([
            {
                "id": 200,
                "type": null,
                "body": format!("{MARKER}A note generated by GitLab"),
                "author": {"id": 99, "username": "project_42_bot"},
                "system": true,
            },
            note(BOT_COMMENTS[2], &format!("{MARKER}The latest bot comment")),
        ])
    }
}

/// Mocks that fail the test if any request is not expected by other mocks.
///
/// These must be created before other mocks.
fn reject_unexpected_requests(server: &mut ServerGuard) -> Vec<Mock> {
    ["GET", "POST", "PUT", "DELETE"]
        .into_iter()
        .map(|method| server.mock(method, Matcher::Any).expect(0).create())
        .collect()
}

fn mock_api(server: &mut ServerGuard, method: &str, path: &str) -> Mock {
    let reset_timestamp = (Utc::now().timestamp() + 60).to_string();
    server
        .mock(
            method,
            format!("/api/v4/projects/{PROJECT_ID}/{path}").as_str(),
        )
        .match_header("PRIVATE-TOKEN", TOKEN)
        .with_header(REMAINING_RATE_LIMIT_HEADER, "50")
        .with_header(RESET_RATE_LIMIT_HEADER, reset_timestamp.as_str())
}

async fn setup(test_params: &TestParams) {
    let mut server = Server::new_async().await;
    unsafe {
        env::set_var("CI_API_V4_URL", format!("{}/api/v4", server.url()));
        env::set_var("CI_PROJECT_ID", PROJECT_ID);
        env::set_var("CI_COMMIT_SHA", SHA);
        if test_params.event_t == EventType::PullRequest {
            env::set_var("CI_MERGE_REQUEST_IID", MR.to_string());
            env::set_var("CI_MERGE_REQUEST_PROJECT_ID", PROJECT_ID);
            // the pipeline of a merge request from a fork runs in the fork
            env::set_var("CI_PROJECT_ID", FORK_PROJECT_ID);
        } else {
            env::remove_var("CI_MERGE_REQUEST_IID");
            env::remove_var("CI_MERGE_REQUEST_PROJECT_ID");
        }
        if test_params.no_token {
            env::remove_var("GITLAB_TOKEN");
        } else {
            env::set_var("GITLAB_TOKEN", TOKEN);
        }
    }
    logger_init();
    log::set_max_level(log::LevelFilter::Debug);
    let client = GitlabApiClient::new().unwrap();

    let mut mocks = reject_unexpected_requests(&mut server);
    let is_mr = test_params.event_t == EventType::PullRequest && !test_params.no_token;
    if is_mr {
        let mock = mock_api(&mut server, "GET", format!("merge_requests/{MR}").as_str());
        mocks.push(if test_params.fail_get_mr {
            mock.with_status(404).create()
        } else {
            mock.with_body(
                json!({
                    "iid": MR,
                    "state": "opened",
                    "draft": false,
                    "discussion_locked": test_params.locked_mr,
                    "diff_refs": null,
                })
                .to_string(),
            )
            .create()
        });
    }
    let notes_path = format!("merge_requests/{MR}/notes");
    let can_comment = is_mr && !test_params.locked_mr && !test_params.fail_get_mr;
    if can_comment {
        for page in [1u8, 2] {
            let mut mock =
                mock_api(&mut server, "GET", &notes_path).match_query(Matcher::AllOf(vec![
                    Matcher::UrlEncoded("sort".to_string(), "asc".to_string()),
                    Matcher::UrlEncoded("page".to_string(), page.to_string()),
                ]));
            if page == 1 {
                mock = mock.with_header(
                    "link",
                    format!(
                        "<{}/api/v4/projects/{PROJECT_ID}/{notes_path}?page=2&sort=asc>; rel=\"next\"",
                        server.url()
                    )
                    .as_str(),
                );
            }
            if test_params.fail_get_existing_comments {
                mocks.push(mock.with_status(403).create());
                break;
            }
            if test_params.bad_existing_comments {
                mocks.push(mock.with_body("not json").create());
                break;
            }
            mocks.push(mock.with_body(existing_comments(page).to_string()).create());
        }
    }
    let comments_found = can_comment
        && !test_params.fail_get_existing_comments
        && !test_params.bad_existing_comments;
    let is_lgtm = test_params.comment_kind == CommentKind::Lgtm;
    let delete_all =
        test_params.comment_policy == CommentPolicy::Anew || (is_lgtm && test_params.no_lgtm);
    if comments_found {
        // Comments are deleted in the order they were posted.
        // When updating, the latest comment is kept.
        let deleted = if delete_all {
            &BOT_COMMENTS[..]
        } else {
            &BOT_COMMENTS[..2]
        };
        for id in deleted {
            mocks.push(
                mock_api(&mut server, "DELETE", format!("{notes_path}/{id}").as_str())
                    .with_status(204)
                    .create(),
            );
        }
    }
    let comment = if is_lgtm { "LGTM" } else { "Attention" };
    let posting =
        can_comment && !test_params.bad_existing_comments && !(is_lgtm && test_params.no_lgtm);
    if posting {
        let (method, path) = if delete_all || !comments_found {
            ("POST", notes_path.clone())
        } else {
            ("PUT", format!("{notes_path}/{}", BOT_COMMENTS[2]))
        };
        mocks.push(if test_params.rate_limited {
            // GitLab's rate limit headers
            server
                .mock(
                    method,
                    format!("/api/v4/projects/{PROJECT_ID}/{path}").as_str(),
                )
                .with_status(429)
                .with_header(REMAINING_RATE_LIMIT_HEADER, "0")
                .with_header(
                    RESET_RATE_LIMIT_HEADER,
                    (Utc::now().timestamp() + 60).to_string().as_str(),
                )
                .create()
        } else {
            mock_api(&mut server, method, &path)
                .match_header("Content-Type", "application/json")
                .match_body(Matcher::Json(json!({"body": format!("{MARKER}{comment}")})))
                .with_status(if test_params.fail_posting { 403 } else { 200 })
                .create()
        });
    }

    let opts = ThreadCommentOptions {
        policy: test_params.comment_policy,
        comment: comment.to_string(),
        kind: test_params.comment_kind,
        marker: MARKER.to_string(),
        no_lgtm: test_params.no_lgtm,
    };
    let result = client.post_thread_comment(opts).await;
    for mock in mocks {
        mock.assert();
    }
    if test_params.no_token && test_params.event_t == EventType::PullRequest {
        assert!(
            matches!(result, Err(RestClientError::EnvVar { .. })),
            "Expected EnvVar error, got: {result:?}"
        );
    } else if test_params.fail_get_mr {
        assert!(
            matches!(result, Err(RestClientError::RequestContext { .. })),
            "Expected RequestContext error, got: {result:?}"
        );
    } else if test_params.rate_limited {
        assert!(
            matches!(result, Err(RestClientError::RateLimitPrimary(_))),
            "Expected RateLimitPrimary error, got: {result:?}"
        );
    } else if test_params.bad_existing_comments {
        assert!(
            matches!(result, Err(RestClientError::Json { .. })),
            "Expected Json error, got: {result:?}"
        );
    } else {
        result.unwrap();
    }
    if test_params.event_t == EventType::Push {
        assert!(
            take_logs()
                .iter()
                .any(|l| l.contains("limited to merge requests only"))
        );
    }
}


//! This submodule declares data structures used to
//! deserialize (and serialize) JSON payload data.

use serde::{Deserialize, Serialize};

/// The possible states of a merge request.
#[derive(Debug, Deserialize, PartialEq, Eq, Clone, Copy)]
#[serde(rename_all = "lowercase")]
pub enum MergeRequestState {
    Opened,
    Closed,
    Merged,
    /// A transitional state while the merge request is being merged.
    Locked,
}

/// The SHAs that describe the version of a merge request's diff.
///
/// These are required when anchoring a comment to a line in the diff.
#[derive(Debug, Deserialize, Serialize, PartialEq, Eq, Clone)]
pub struct DiffRefs {
    pub base_sha: String,
    pub head_sha: String,
    pub start_sha: String,
}

/// A structure for deserializing a merge request's info from a response's json.
#[derive(Debug, Deserialize, PartialEq, Eq, Clone)]
pub struct MergeRequestInfo {
    pub draft: bool,
    pub state: MergeRequestState,
    /// `null` unless the discussions were explicitly (un)locked.
    pub discussion_locked: Option<bool>,
    /// `null` until GitLab has finished computing the merge request's diff.
    pub diff_refs: Option<DiffRefs>,
}

impl MergeRequestInfo {
    pub fn is_locked(&self) -> bool {
        self.discussion_locked.unwrap_or_default()
    }

    pub fn is_closed(&self) -> bool {
        matches!(
            self.state,
            MergeRequestState::Closed | MergeRequestState::Merged
        )
    }
}

/// A structure for deserializing a note's author from a response's json.
///
/// This is only used for debug output.
#[derive(Debug, Deserialize, PartialEq, Eq, Clone)]
pub struct User {
    pub username: String,
    pub id: u64,
}

/// A structure for deserializing a note (a comment) from a response's json.
#[derive(Debug, Deserialize, PartialEq, Eq, Clone)]
pub struct Note {
    pub id: u64,
    pub body: String,
    pub author: User,
    /// The kind of note: `DiffNote` (on a line of the diff), `DiscussionNote` (in a thread),
    /// or `null` (a regular comment).
    #[serde(rename = "type", default)]
    pub kind: Option<String>,
    /// Is this note generated by GitLab (eg. "added 1 commit")?
    #[serde(default)]
    pub system: bool,
    /// The position in the diff, if this is a note on a line of the diff.
    #[serde(default)]
    pub position: Option<NotePosition>,
    #[serde(default)]
    pub resolvable: bool,
    #[serde(default)]
    pub resolved: bool,
}

/// The position of a note in a merge request's diff.
#[derive(Debug, Deserialize, PartialEq, Eq, Clone)]
pub struct NotePosition {
    pub new_path: Option<String>,
    pub new_line: Option<u32>,
}

/// A structure for deserializing a thread of notes from a response's json.
#[derive(Debug, Deserialize, PartialEq, Eq, Clone)]
pub struct Discussion {
    pub id: String,
    pub notes: Vec<Note>,
}

impl Discussion {
    /// Is this thread resolved?
    ///
    /// Like GitLab, a thread is considered resolved when all its resolvable notes are resolved.
    pub fn is_resolved(&self) -> bool {
        let mut resolvable = self.notes.iter().filter(|n| n.resolvable).peekable();
        resolvable.peek().is_some() && resolvable.all(|n| n.resolved)
    }
}

/// A structure for serializing a draft note's position in the diff.
#[derive(Debug, Serialize, PartialEq, Eq, Clone)]
pub struct DraftNotePosition {
    #[serde(flatten)]
    pub diff_refs: DiffRefs,
    pub position_type: &'static str,
    pub old_path: String,
    pub new_path: String,
    /// Only set for lines that exist in both versions of the file.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub old_line: Option<u32>,
    pub new_line: u32,
}

/// A structure for serializing a draft note (a pending review comment).
#[derive(Debug, Serialize, PartialEq, Eq, Clone)]
pub struct DraftNote {
    pub note: String,
    pub position: DraftNotePosition,
}

/// A structure for deserializing an existing draft note from a response's json.
#[derive(Debug, Deserialize, PartialEq, Eq, Clone)]
pub struct ExistingDraftNote {
    pub id: u64,
    pub note: String,
}

/// A structure for deserializing a single changed file in a commit.
#[cfg(feature = "file-changes")]
#[derive(Debug, Deserialize, PartialEq, Eq, Clone)]
pub struct CommitDiff {
    pub old_path: String,
    pub new_path: String,
    /// The file's patch.
    ///
    /// This is empty when there is no change to the file's content, or
    /// when GitLab omits the patch because it is too large.
    pub diff: String,
    #[serde(default)]
    pub deleted_file: bool,
    /// Was the patch omitted because it exceeds GitLab's "safe" diff limits?
    ///
    /// Not present in responses from GitLab versions older than 18.4.
    #[serde(default)]
    pub collapsed: bool,
    /// Was the patch omitted because it exceeds GitLab's diff limits?
    ///
    /// Not present in responses from GitLab versions older than 18.4.
    #[serde(default)]
    pub too_large: bool,
}
